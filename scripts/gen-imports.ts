// Generates src/generated/{async,sqlite}-imports.ts from moonrun's import registries
// at the pinned moon commit (upstream.lock.json). Linux `#[cfg]` arms are selected.
//
//   node scripts/gen-imports.ts [--moon-repo <path>] [--check]
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import * as path from 'node:path';

const repoRoot = path.resolve(import.meta.dirname, '..');
const lock = JSON.parse(readFileSync(path.join(repoRoot, 'upstream.lock.json'), 'utf8')) as {
  moon: { commit: string };
};
const argv = process.argv.slice(2);
const moonRepo = argv.includes('--moon-repo')
  ? (argv[argv.indexOf('--moon-repo') + 1] ?? '')
  : path.join(process.env['HOME'] ?? '', 'ghq/github.com/moonbitlang/moon');
const check = argv.includes('--check');

type Kind = 'ported' | 'compat' | 'helper' | 'fake' | 'sqlite';
interface Entry {
  readonly kind: Kind;
  readonly callback: string;
  readonly params: ReadonlyArray<readonly [string, string]>;
  readonly result: string;
  readonly symbol: string;
}

function show(file: string): string {
  return execFileSync('git', ['-C', moonRepo, 'show', `${lock.moon.commit}:${file}`], {
    encoding: 'utf8',
  });
}

/** Evaluates a cfg predicate for the v8 backend on Linux. */
function cfgOnLinux(expr: string): boolean {
  const e = expr.trim();
  const call = /^(not|all|any)\((.*)\)$/s.exec(e);
  if (call !== null) {
    const [, op, inner = ''] = call;
    const parts = splitTopLevel(inner);
    if (op === 'not') {
      return !cfgOnLinux(parts[0] ?? '');
    }
    return op === 'all' ? parts.every(cfgOnLinux) : parts.some(cfgOnLinux);
  }
  switch (e.replace(/\s+/g, '')) {
    case 'unix':
    case 'target_os="linux"':
    case 'feature="v8"':
      return true;
    case 'windows':
    case 'test':
    case 'feature="wasmtime"':
      return false;
    default:
      if (/^target_os="/.test(e.replace(/\s+/g, ''))) {
        return false;
      }
      throw new Error(`unknown cfg predicate: ${e}`);
  }
}

function splitTopLevel(s: string): string[] {
  const out: string[] = [];
  let depth = 0;
  let cur = '';
  for (const ch of s) {
    if (ch === '(') depth++;
    if (ch === ')') depth--;
    if (ch === ',' && depth === 0) {
      out.push(cur);
      cur = '';
    } else {
      cur += ch;
    }
  }
  if (cur.trim() !== '') out.push(cur);
  return out;
}

function macroBody(source: string, macro: string): string {
  const start = source.indexOf(`${macro}! {`);
  if (start < 0) throw new Error(`macro ${macro} not found`);
  let depth = 0;
  for (let i = source.indexOf('{', start); i < source.length; i++) {
    if (source[i] === '{') depth++;
    if (source[i] === '}' && --depth === 0) return source.slice(source.indexOf('{', start) + 1, i);
  }
  throw new Error(`unterminated ${macro}`);
}

function parseEntries(body: string, withKind: boolean): Entry[] {
  const withoutComments = body.replace(/\/\/[^\n]*/g, '');
  const entries: Entry[] = [];
  const re = withKind
    ? /((?:#\[cfg\((?:[^()]|\([^()]*(?:\([^()]*\))*[^()]*\))*\)\]\s*)*)(ported|compat|helper|fake)\s+([\w:]+)\s*\(([^)]*)\)\s*->\s*(\w+)\s*=>\s*"([^"]+)"\s*;/g
    : /((?:#\[cfg\((?:[^()]|\([^()]*(?:\([^()]*\))*[^()]*\))*\)\]\s*)*)()([\w:]+)\s*\(([^)]*)\)\s*->\s*(\w+)\s*=>\s*"([^"]+)"\s*;/g;
  for (const m of withoutComments.matchAll(re)) {
    const [, attrs = '', kind = '', callback = '', params = '', result = '', symbol = ''] = m;
    const cfgs = [
      ...attrs.matchAll(/#\[cfg\(((?:[^()]|\([^()]*(?:\([^()]*\))*[^()]*\))*)\)\]/g),
    ].map((c) => c[1] ?? '');
    if (!cfgs.every(cfgOnLinux)) continue;
    const parsedParams = params
      .split(',')
      .map((p) => p.trim())
      .filter((p) => p !== '')
      .map((p) => {
        const [name = '', type = ''] = p.split(':').map((x) => x.trim());
        return [name, type] as const;
      });
    entries.push({
      kind: (withKind ? kind : 'sqlite') as Kind,
      callback,
      params: parsedParams,
      result,
      symbol,
    });
  }
  return entries;
}

function emit(name: string, module: string, entries: readonly Entry[], source: string): string {
  const seen = new Map<string, Entry>();
  for (const e of entries) {
    if (seen.has(e.symbol)) throw new Error(`duplicate Linux entry for ${e.symbol}`);
    seen.set(e.symbol, e);
  }
  const lines = [...seen.values()]
    .sort((a, b) => (a.symbol < b.symbol ? -1 : a.symbol > b.symbol ? 1 : 0))
    .map((e) => {
      const params = e.params.map(([n, t]) => `['${n}', '${t}']`).join(', ');
      return `  '${e.symbol}': { kind: '${e.kind}', params: [${params}], result: '${e.result}' },`;
    });
  return `// Generated by scripts/gen-imports.ts from ${source} at moon ${lock.moon.commit}. Do not edit.

export const ${name}_MODULE = '${module}';

export const ${name}_IMPORTS = {
${lines.join('\n')}
} as const;
`;
}

const outputs: Array<readonly [string, string]> = [];
{
  const file = 'crates/moonrun/src/async_api/registry.rs';
  const entries = parseEntries(macroBody(show(file), 'declare_async_imports'), true);
  outputs.push([
    'src/generated/async-imports.ts',
    emit('ASYNC', 'moonbitlang/async', entries, file),
  ]);
}
{
  const file = 'crates/moonrun/src/sqlite/wasm/registry.rs';
  const entries = parseEntries(macroBody(show(file), 'declare_sqlite_imports'), false);
  outputs.push([
    'src/generated/sqlite-imports.ts',
    emit('SQLITE', 'moonbitlang/sqlite', entries, file),
  ]);
}

let stale = false;
for (const [rel, text] of outputs) {
  const target = path.join(repoRoot, rel);
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {}
  if (current !== text) {
    stale = true;
    if (!check) writeFileSync(target, text);
  }
  console.log(
    `${rel}: ${(text.match(/^ {2}'/gm) ?? []).length} imports${current === text ? '' : check ? ' (stale)' : ' (written)'}`,
  );
}
if (check && stale) process.exit(1);
